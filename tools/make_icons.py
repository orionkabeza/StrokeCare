#!/usr/bin/env python3
"""Build frontend/site/js/icons.js from Phosphor's SVG files (MIT licence, https://phosphoricons.com).

Owner: Orion Kabeza (DevOps) · AI-assisted draft, see AI_USE_LOG.md

The app draws its icons inline from this one generated file, so there is no icon library to install and no build
step. Only the icons the app uses are kept, in the four weights it needs. To add an icon, add its name to NAMES and run:

    npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz
    python tools/make_icons.py package/assets > frontend/site/js/icons.js
"""
import re
import sys
from pathlib import Path

NAMES = """arrow-counter-clockwise bed bell bell-ringing book-open-text calendar-check caret-left caret-right chart-bar
chat-circle chat-circle-text check check-circle circle-half clipboard-text cloud-arrow-down cloud-arrow-up copy
download-simple drop fork-knife funnel hand-heart hand-palm hand-pointing hand-waving heartbeat hourglass house info key
link-break list-checks magnifying-glass map-pin microphone moon moon-stars note-pencil paper-plane-right
person-simple-walk phone-call pill play plus printer question share-network shield-check sign-in sign-out siren
smiley-sad speaker-high stethoscope stop sun target text-aa thermometer-cold thermometer-hot toilet trash user-circle
user-plus users-three wifi-slash x""".split()
WEIGHTS = ("regular", "duotone", "fill", "bold")


def inner(svg: str) -> str:
    return re.sub(r"</?svg[^>]*>", "", svg).strip().replace("\n", "")


def main(assets: Path) -> None:
    print("// Generated by tools/make_icons.py from Phosphor Icons (MIT). Do not edit by hand.")
    print("// Each entry holds the inside of a 256 x 256 SVG, in the weights the app uses.")
    print("export const ICONS = {")
    for name in NAMES:
        parts = []
        for weight in WEIGHTS:
            file = assets / weight / (f"{name}.svg" if weight == "regular" else f"{name}-{weight}.svg")
            if not file.exists():
                sys.exit(f"missing icon: {file}")
            parts.append(f"{weight}: '{inner(file.read_text())}'")
        print(f"  '{name}': {{ {', '.join(parts)} }},")
    print("}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
